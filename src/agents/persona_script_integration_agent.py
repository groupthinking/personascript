"""
PersonaScriptIntegrationAgent - Orchestrates functional API integrations
with HubSpot CRM and Contentful CMS for content deployment from PersonaScript.

Follows a 10-step execution plan:
1. Parse inputs to understand content structures and target models.
2. Establish authenticated connection to HubSpot API.
3. Establish authenticated connection to Contentful Management API.
4. Design content mapping strategy for HubSpot objects.
5. Design content mapping strategy for Contentful models.
6. Publish content to HubSpot via API.
7. Publish content to Contentful via Management API.
8. Execute suite of unit and integration tests verifying data integrity.
9. Generate detailed integration documentation (setup, mapping, usage, troubleshooting).
10. Create GitHub issue detailing integration status, outputs, and execution steps.
"""

import os
import logging
from typing import Dict, List, Optional, Any
from dataclasses import dataclass, field
from datetime import datetime, timezone

from ..integrations.hubspot_integration import HubSpotIntegration
from ..integrations.contentful_integration import ContentfulIntegration
from ..integrations.github_integration import GitHubIntegration

logger = logging.getLogger(__name__)


@dataclass
class PersonaScriptContent:
    """Represents internal PersonaScript content schema."""
    id: str
    content_type: str  # "blog_post", "email", "landing_page"
    title: str
    body: str
    summary: Optional[str] = None
    author: Optional[str] = None
    slug: Optional[str] = None
    cta_text: Optional[str] = None
    cta_url: Optional[str] = None
    target_audience: Optional[str] = None
    custom_fields: Dict[str, Any] = field(default_factory=dict)


@dataclass
class HubSpotObjectDefinition:
    """Target object definitions for HubSpot CRM/CMS."""
    object_type: str  # e.g., "blog_post", "marketing_email", "landing_page"
    property_mappings: Dict[str, str] = field(default_factory=dict)
    required_properties: List[str] = field(default_factory=list)


@dataclass
class ContentfulContentModel:
    """Target content model definitions for Contentful CMS."""
    content_type_id: str  # e.g., "blogPost", "marketingEmail", "landingPage"
    field_mappings: Dict[str, str] = field(default_factory=dict)
    required_fields: List[str] = field(default_factory=list)


@dataclass
class IntegrationTestResult:
    """Represents a pass/fail result from deployment verification tests."""
    platform: str  # "HubSpot" or "Contentful"
    test_name: str
    status: str  # "PASS" or "FAIL"
    details: str
    item_id: Optional[str] = None
    payload_preview: Optional[Dict[str, Any]] = None


@dataclass
class AgentInputs:
    """Inputs for the PersonaScriptIntegrationAgent."""
    content_items: List[PersonaScriptContent]
    hubspot_api_key: Optional[str] = None
    hubspot_access_token: Optional[str] = None
    contentful_space_id: Optional[str] = None
    contentful_management_token: Optional[str] = None
    contentful_environment: Optional[str] = "master"
    hubspot_object_definitions: Optional[Dict[str, HubSpotObjectDefinition]] = None
    contentful_content_models: Optional[Dict[str, ContentfulContentModel]] = None
    locale: str = "en-US"
    auto_publish_contentful: bool = True
    github_token: Optional[str] = None
    github_repo: Optional[str] = None


@dataclass
class AgentOutputs:
    """Outputs generated by PersonaScriptIntegrationAgent."""
    confirmation_message: str
    integration_test_results: List[IntegrationTestResult]
    published_hubspot_items: List[Dict[str, Any]]
    published_contentful_items: List[Dict[str, Any]]
    documentation_markdown: str
    github_issue_url: str
    execution_log: List[Dict[str, Any]]
    status: str = "success"
    error_message: Optional[str] = None


class PersonaScriptIntegrationAgent:
    """
    Main agent for developing, executing, and documenting API integrations
    with HubSpot CRM and Contentful CMS.
    """

    def __init__(
        self,
        hubspot_api_key: Optional[str] = None,
        hubspot_access_token: Optional[str] = None,
        contentful_space_id: Optional[str] = None,
        contentful_management_token: Optional[str] = None,
        contentful_environment: Optional[str] = "master",
        github_token: Optional[str] = None,
        github_repo: Optional[str] = None
    ):
        """Initialize PersonaScriptIntegrationAgent with API credentials."""
        self.hubspot_api_key = hubspot_api_key or os.environ.get("HUBSPOT_API_KEY")
        self.hubspot_access_token = hubspot_access_token or os.environ.get("HUBSPOT_ACCESS_TOKEN")
        self.contentful_space_id = contentful_space_id or os.environ.get("CONTENTFUL_SPACE_ID")
        self.contentful_management_token = contentful_management_token or os.environ.get("CONTENTFUL_MANAGEMENT_TOKEN")
        self.contentful_environment = contentful_environment or os.environ.get("CONTENTFUL_ENVIRONMENT", "master")

        self.github_token = github_token or os.environ.get("GITHUB_TOKEN")
        self.github_repo = github_repo or os.environ.get("GITHUB_REPO", "groupthinking/personascript")

        self.execution_log: List[Dict[str, Any]] = []
        logger.info("PersonaScriptIntegrationAgent initialized")

    def _log_step(self, step_number: int, description: str, status: str = "started", data: Optional[Dict] = None):
        """Record an execution step in the execution log."""
        log_entry = {
            "step": step_number,
            "description": description,
            "status": status,
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "data": data or {}
        }
        self.execution_log.append(log_entry)
        logger.info(f"Step {step_number}: {description} - {status}")

    def execute(self, inputs: AgentInputs) -> AgentOutputs:
        """
        Execute the complete 10-step integration workflow.

        Args:
            inputs: AgentInputs containing content items and target definitions.

        Returns:
            AgentOutputs containing test results, published payloads, docs, and GitHub issue URL.
        """
        logger.info("Starting PersonaScriptIntegrationAgent execution")
        self.execution_log = []

        try:
            # Step 1: Parse provided inputs
            self._log_step(1, "Parse provided inputs and content structures")
            parsed_inputs = self._parse_inputs(inputs)
            self._log_step(1, "Parse provided inputs and content structures", "completed", {
                "items_count": len(parsed_inputs["content_items"])
            })

            # Step 2: Establish authenticated connection to HubSpot API
            self._log_step(2, "Establish authenticated connection to HubSpot API")
            hs_key = inputs.hubspot_api_key or self.hubspot_api_key
            hs_token = inputs.hubspot_access_token or self.hubspot_access_token
            hubspot_integration = HubSpotIntegration(api_key=hs_key, access_token=hs_token)
            hs_conn_test = hubspot_integration.test_connection()
            self._log_step(2, "Establish authenticated connection to HubSpot API", "completed", hs_conn_test)

            # Step 3: Establish authenticated connection to Contentful Management API
            self._log_step(3, "Establish authenticated connection to Contentful Management API")
            ct_space = inputs.contentful_space_id or self.contentful_space_id
            ct_token = inputs.contentful_management_token or self.contentful_management_token
            ct_env = inputs.contentful_environment or self.contentful_environment
            contentful_integration = ContentfulIntegration(
                space_id=ct_space, management_token=ct_token, environment=ct_env
            )
            ct_conn_test = contentful_integration.test_connection()
            self._log_step(3, "Establish authenticated connection to Contentful Management API", "completed", ct_conn_test)

            # Step 4: Design content mapping strategy for HubSpot objects
            self._log_step(4, "Design content mapping strategy for HubSpot objects")
            hubspot_mappings = parsed_inputs["hubspot_object_definitions"]
            mapped_hubspot_payloads = self._map_content_to_hubspot(
                parsed_inputs["content_items"], hubspot_mappings
            )
            self._log_step(4, "Design content mapping strategy for HubSpot objects", "completed", {
                "mapped_payloads_count": len(mapped_hubspot_payloads)
            })

            # Step 5: Design content mapping strategy for Contentful models
            self._log_step(5, "Design content mapping strategy for Contentful models")
            contentful_models = parsed_inputs["contentful_content_models"]
            mapped_contentful_payloads = self._map_content_to_contentful(
                parsed_inputs["content_items"], contentful_models, inputs.locale
            )
            self._log_step(5, "Design content mapping strategy for Contentful models", "completed", {
                "mapped_payloads_count": len(mapped_contentful_payloads)
            })

            # Step 6: Implement core publishing logic to HubSpot
            self._log_step(6, "Publish content to HubSpot API")
            published_hubspot_items = self._publish_to_hubspot(
                hubspot_integration, mapped_hubspot_payloads
            )
            self._log_step(6, "Publish content to HubSpot API", "completed", {
                "published_count": len(published_hubspot_items)
            })

            # Step 7: Implement core publishing logic to Contentful
            self._log_step(7, "Publish content to Contentful Management API")
            published_contentful_items = self._publish_to_contentful(
                contentful_integration, mapped_contentful_payloads, inputs.locale, inputs.auto_publish_contentful
            )
            self._log_step(7, "Publish content to Contentful Management API", "completed", {
                "published_count": len(published_contentful_items)
            })

            # Step 8: Develop and execute integration test suite
            self._log_step(8, "Execute suite of integration tests")
            test_results = self._run_integration_tests(
                parsed_inputs["content_items"],
                published_hubspot_items,
                published_contentful_items,
                hs_conn_test,
                ct_conn_test
            )
            self._log_step(8, "Execute suite of integration tests", "completed", {
                "total_tests": len(test_results),
                "passed_tests": len([t for t in test_results if t.status == "PASS"])
            })

            # Step 9: Generate detailed integration documentation
            self._log_step(9, "Generate detailed integration documentation")
            documentation_md = self._generate_documentation(
                hubspot_mappings, contentful_models, test_results
            )
            self._log_step(9, "Generate detailed integration documentation", "completed")

            # Step 10: Create GitHub issue summarizing execution and status
            self._log_step(10, "Create GitHub issue detailing integration status")
            git_token = inputs.github_token or self.github_token
            git_repo = inputs.github_repo or self.github_repo
            github_integration = GitHubIntegration(token=git_token, repo=git_repo)

            github_issue_url = self._create_github_issue(
                github_integration,
                test_results,
                published_hubspot_items,
                published_contentful_items,
                documentation_md,
                inputs
            )
            self._log_step(10, "Create GitHub issue detailing integration status", "completed", {
                "issue_url": github_issue_url
            })

            confirmation_msg = (
                f"Successfully developed, executed, and verified HubSpot and Contentful API integrations. "
                f"Deployed {len(published_hubspot_items)} items to HubSpot and "
                f"{len(published_contentful_items)} items to Contentful. "
                f"Executed {len(test_results)} integration tests ({len([t for t in test_results if t.status == 'PASS'])} passed)."
            )

            logger.info("PersonaScriptIntegrationAgent execution completed successfully")
            return AgentOutputs(
                confirmation_message=confirmation_msg,
                integration_test_results=test_results,
                published_hubspot_items=published_hubspot_items,
                published_contentful_items=published_contentful_items,
                documentation_markdown=documentation_md,
                github_issue_url=github_issue_url,
                execution_log=self.execution_log,
                status="success"
            )

        except Exception as e:
            logger.error(f"Error during PersonaScriptIntegrationAgent execution: {e}", exc_info=True)
            return AgentOutputs(
                confirmation_message="Integration execution encountered an error.",
                integration_test_results=[],
                published_hubspot_items=[],
                published_contentful_items=[],
                documentation_markdown="",
                github_issue_url="",
                execution_log=self.execution_log,
                status="error",
                error_message=str(e)
            )

    def _parse_inputs(self, inputs: AgentInputs) -> Dict[str, Any]:
        """Step 1: Parse and supply default object definitions and models if missing."""
        content_items = inputs.content_items or []

        # Default HubSpot Object Definitions
        default_hs_defs = {
            "blog_post": HubSpotObjectDefinition(
                object_type="blog_post",
                property_mappings={"title": "name", "body": "postBody", "summary": "metaDescription", "slug": "slug"},
                required_properties=["name", "postBody"]
            ),
            "email": HubSpotObjectDefinition(
                object_type="marketing_email",
                property_mappings={"title": "name", "body": "body", "summary": "subject"},
                required_properties=["name", "body"]
            ),
            "landing_page": HubSpotObjectDefinition(
                object_type="landing_page",
                property_mappings={"title": "name", "body": "pageBody", "slug": "slug"},
                required_properties=["name", "pageBody"]
            )
        }
        if inputs.hubspot_object_definitions:
            default_hs_defs.update(inputs.hubspot_object_definitions)

        # Default Contentful Content Models
        default_ct_models = {
            "blog_post": ContentfulContentModel(
                content_type_id="blogPost",
                field_mappings={"title": "title", "body": "body", "summary": "excerpt", "author": "author", "slug": "slug"},
                required_fields=["title", "body"]
            ),
            "email": ContentfulContentModel(
                content_type_id="marketingEmail",
                field_mappings={"title": "title", "body": "content", "summary": "subjectLine", "cta_url": "ctaUrl"},
                required_fields=["title", "content"]
            ),
            "landing_page": ContentfulContentModel(
                content_type_id="landingPage",
                field_mappings={"title": "title", "body": "content", "slug": "slug", "cta_text": "ctaButtonText"},
                required_fields=["title", "content"]
            )
        }
        if inputs.contentful_content_models:
            default_ct_models.update(inputs.contentful_content_models)

        return {
            "content_items": content_items,
            "hubspot_object_definitions": default_hs_defs,
            "contentful_content_models": default_ct_models
        }

    def _map_content_to_hubspot(
        self,
        items: List[PersonaScriptContent],
        definitions: Dict[str, HubSpotObjectDefinition]
    ) -> List[Dict[str, Any]]:
        """Step 4: Map PersonaScript internal schema to HubSpot object properties."""
        mapped_list = []
        for item in items:
            ctype = item.content_type.lower()
            obj_def = definitions.get(ctype) or definitions.get("blog_post")
            target_type = obj_def.object_type if obj_def else "blog_post"

            payload: Dict[str, Any] = {}
            if obj_def and obj_def.property_mappings:
                for src_field, target_prop in obj_def.property_mappings.items():
                    val = getattr(item, src_field, None)
                    if val is None and item.custom_fields:
                        val = item.custom_fields.get(src_field)
                    if val is not None:
                        payload[target_prop] = val

            # Ensure basic fallback values if mapping missed them
            if "name" not in payload and "title" not in payload:
                payload["name"] = item.title
            if "body" not in payload and "postBody" not in payload and "pageBody" not in payload:
                payload["body"] = item.body
            if "slug" not in payload and item.slug:
                payload["slug"] = item.slug

            mapped_list.append({
                "item_id": item.id,
                "content_type": ctype,
                "target_object_type": target_type,
                "payload": payload
            })
        return mapped_list

    def _map_content_to_contentful(
        self,
        items: List[PersonaScriptContent],
        models: Dict[str, ContentfulContentModel],
        locale: str
    ) -> List[Dict[str, Any]]:
        """Step 5: Map PersonaScript internal schema to Contentful localized content model fields."""
        mapped_list = []
        for item in items:
            ctype = item.content_type.lower()
            model_def = models.get(ctype) or models.get("blog_post")
            content_type_id = model_def.content_type_id if model_def else "blogPost"

            fields_payload: Dict[str, Any] = {}
            if model_def and model_def.field_mappings:
                for src_field, target_field in model_def.field_mappings.items():
                    val = getattr(item, src_field, None)
                    if val is None and item.custom_fields:
                        val = item.custom_fields.get(src_field)
                    if val is not None:
                        fields_payload[target_field] = val

            # Fallbacks if default mappings omitted key attributes
            if "title" not in fields_payload:
                fields_payload["title"] = item.title
            if "body" not in fields_payload and "content" not in fields_payload:
                fields_payload["body"] = item.body

            mapped_list.append({
                "item_id": item.id,
                "content_type": ctype,
                "content_type_id": content_type_id,
                "fields": fields_payload
            })
        return mapped_list

    def _publish_to_hubspot(
        self,
        hubspot_integration: HubSpotIntegration,
        mapped_payloads: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:
        """Step 6: Publish mapped payloads to HubSpot CRM/CMS."""
        published = []
        for mapped in mapped_payloads:
            result = hubspot_integration.publish_content(
                content_type=mapped["target_object_type"],
                payload=mapped["payload"]
            )
            published.append({
                "item_id": mapped["item_id"],
                "target_object_type": mapped["target_object_type"],
                "hubspot_response": result
            })
        return published

    def _publish_to_contentful(
        self,
        contentful_integration: ContentfulIntegration,
        mapped_payloads: List[Dict[str, Any]],
        locale: str,
        auto_publish: bool
    ) -> List[Dict[str, Any]]:
        """Step 7: Publish mapped payloads to Contentful Management API."""
        published = []
        for mapped in mapped_payloads:
            result = contentful_integration.publish_content(
                content_type_id=mapped["content_type_id"],
                payload=mapped["fields"],
                locale=locale,
                auto_publish=auto_publish
            )
            published.append({
                "item_id": mapped["item_id"],
                "content_type_id": mapped["content_type_id"],
                "contentful_response": result
            })
        return published

    def _run_integration_tests(
        self,
        items: List[PersonaScriptContent],
        hubspot_results: List[Dict[str, Any]],
        contentful_results: List[Dict[str, Any]],
        hs_conn: Dict[str, Any],
        ct_conn: Dict[str, Any]
    ) -> List[IntegrationTestResult]:
        """Step 8: Develop and execute unit/integration test suite verifying data integrity."""
        tests = []

        # Test 1: HubSpot Authentication Test
        hs_conn_ok = hs_conn.get("status") in ("connected", "success")
        tests.append(IntegrationTestResult(
            platform="HubSpot",
            test_name="HubSpot API Authentication & Connection Test",
            status="PASS" if hs_conn_ok else "FAIL",
            details=f"HubSpot connection test status: {hs_conn.get('message', 'N/A')} (mode: {hs_conn.get('mode')})"
        ))

        # Test 2: Contentful Authentication Test
        ct_conn_ok = ct_conn.get("status") in ("connected", "success")
        tests.append(IntegrationTestResult(
            platform="Contentful",
            test_name="Contentful Management API Authentication Test",
            status="PASS" if ct_conn_ok else "FAIL",
            details=f"Contentful connection test status: {ct_conn.get('message', 'N/A')} (mode: {ct_conn.get('mode')})"
        ))

        # Test 3 & 4: Payload integrity and field population tests
        item_map = {item.id: item for item in items}

        for hs_res in hubspot_results:
            item_id = hs_res["item_id"]
            resp = hs_res["hubspot_response"]
            item = item_map.get(item_id)
            title = item.title if item else "Unknown"

            # Check field population in payload
            payload = resp.get("payload", {})
            has_name = bool(payload.get("name") or payload.get("subject") or payload.get("htmlTitle"))
            has_id = bool(resp.get("id"))

            status = "PASS" if (has_name and has_id) else "FAIL"
            tests.append(IntegrationTestResult(
                platform="HubSpot",
                test_name=f"HubSpot Deployment & Field Population - '{title}'",
                status=status,
                item_id=item_id,
                details=f"Deployed object ID: {resp.get('id')}, Status: {resp.get('status')}, URL: {resp.get('url')}",
                payload_preview=payload
            ))

        for ct_res in contentful_results:
            item_id = ct_res["item_id"]
            resp = ct_res["contentful_response"]
            item = item_map.get(item_id)
            title = item.title if item else "Unknown"

            fields = resp.get("fields", {})
            has_fields = bool(fields)
            has_id = bool(resp.get("id"))

            status = "PASS" if (has_fields and has_id) else "FAIL"
            tests.append(IntegrationTestResult(
                platform="Contentful",
                test_name=f"Contentful Localized Entry Creation & Publish - '{title}'",
                status=status,
                item_id=item_id,
                details=f"Created Entry ID: {resp.get('id')}, Version: {resp.get('version')}, Entry Status: {resp.get('status')}",
                payload_preview=fields
            ))

        return tests

